#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Pick "Related reading" candidates for every post (_data/related.yml), drawn by
_includes/related-posts.html as three cards at the end of each post.

    python3 scripts/build_related.py          # rewrites _data/related.yml

Re-run it whenever a post is added or retitled (check_posts.py warns when a
post has no entry). Method: TF-IDF over each post's title, term, description
and body (Liquid tags, code blocks and markup stripped), cosine similarity,
best first. Each post gets MAX_CANDIDATES slugs, more than the three shown, because
the include skips candidates that aren't published yet (future: false) and
the post's own previous/next-in-series links, which already sit just above
the cards. Earlier-dated posts get a small boost so a new post links back
to what it builds on rather than only forward.
"""
import math
import re
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
POSTS = ROOT / "_posts"
OUT = ROOT / "_data" / "related.yml"
MAX_CANDIDATES = 8
EARLIER_BOOST = 1.1

STOP = set("""a about above after again against all also am an and any are as at be because been
before being below between both but by can could did do does doing down during each few for from
further had has have having he her here hers him his how i if in into is it its itself just me more
most my no nor not now of off on once only or other our out over own same she should so some such
than that the their them then there these they this those through to too under until up very was we
were what when where which while who whom why will with you your yours it's don't isn't doesn't
can't won't one two three four five six seven eight nine ten first second third per year years
post posts series blog worked example here's that's what's we'll you'll you're they're let's""".split())

FM = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def clean(body):
    body = re.sub(r"```.*?```", " ", body, flags=re.S)
    body = re.sub(r"\{%.*?%\}|\{\{.*?\}\}", " ", body, flags=re.S)
    body = re.sub(r"<[^>]+>", " ", body)
    body = re.sub(r"\]\([^)]*\)", "]", body)  # keep link text, drop URLs
    return body.lower()


def tokens(text):
    return [w for w in re.findall(r"[a-z][a-z0-9/&'-]+", text) if w not in STOP and len(w) > 2]


def main():
    docs = []
    for f in sorted(POSTS.glob("*.markdown")):
        s = f.read_text(encoding="utf-8")
        m = FM.match(s)
        fm = yaml.safe_load(m.group(1)) if m else {}
        slug = re.sub(r"^\d{4}-\d\d-\d\d-", "", f.stem)
        head = " ".join(str(fm.get(k, "")) for k in ("title", "term", "description"))
        # Title, term and description count three times: they say what the post is about.
        toks = tokens(clean(head)) * 3 + tokens(clean(s[m.end():] if m else s))
        docs.append((f.stem[:10], slug, Counter(toks)))

    n = len(docs)
    df = Counter(t for _, _, c in docs for t in c)
    idf = {t: math.log(n / d) for t, d in df.items() if d > 1}  # a word in one post links nothing
    vecs = []
    for _, _, c in docs:
        v = {t: (1 + math.log(k)) * idf[t] for t, k in c.items() if t in idf}
        norm = math.sqrt(sum(x * x for x in v.values())) or 1.0
        vecs.append({t: x / norm for t, x in v.items()})

    related = {}
    for i, (date, slug, _) in enumerate(docs):
        scores = []
        for j, (d2, s2, _) in enumerate(docs):
            if i == j:
                continue
            a, b = vecs[i], vecs[j]
            if len(a) > len(b):
                a, b = b, a
            sim = sum(x * b.get(t, 0.0) for t, x in a.items())
            if d2 <= date:
                sim *= EARLIER_BOOST
            scores.append((sim, s2))
        scores.sort(key=lambda x: (-x[0], x[1]))
        related[slug] = [s for _, s in scores[:MAX_CANDIDATES]]

    assert len(related) == n and all(len(v) == MAX_CANDIDATES for v in related.values())
    assert all(slug not in v for slug, v in related.items())
    header = ("# Generated by scripts/build_related.py: do not edit by hand, re-run the script.\n"
              "# post slug -> related post slugs, most similar first (see _includes/related-posts.html).\n")
    OUT.write_text(header + yaml.safe_dump(related, sort_keys=True, allow_unicode=True, width=200),
                   encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} posts x {MAX_CANDIDATES} candidates")


if __name__ == "__main__":
    main()
