#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Build _data/tool_defaults.json — the starting inputs for the on-page calculators
(assets/js/calc.js) and the cases each one must reproduce.

WHY: a calculator's default inputs are its post's worked example, and CLAUDE.md's
rule is that a reader recomputing an example gets the post's answer. Rates in
the posts are displayed rounded (7.1%, 5%), and plugging those back in lands a
few hundred rupees off. So the defaults here are derived from the same data the
post uses, with the FEWEST decimals that still reproduce every figure the post
shows (to the rupee, or to the decimal the post displays). The script fails if
no precision up to 6 decimals does.

Each calculator's `cases` are checked twice: here, with a Python mirror of the
formulas (to choose the precision), and by scripts/check_tools.mjs, which runs
the real JavaScript in Node against the same cases.

    python3 scripts/derive_tool_defaults.py     # rewrites _data/tool_defaults.json

Inputs: _data/risk.yml (losses, leverage), _data/risk2.yml (inflation, incl. the
unrounded growth_factor / cpi_factor that scripts/derive_risk2.py writes for this),
assets/data/parag-parikh-flexicap-nav.csv (expense ratio). Re-run after any of
those change.
"""
import csv
import json
import os
from datetime import date

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "_data", "tool_defaults.json")


def load(name):
    return yaml.safe_load(open(os.path.join(ROOT, "_data", name), encoding="utf-8"))


risk, risk2, mf = load("risk.yml"), load("risk2.yml"), load("mf.yml")

# ---- Python mirror of assets/js/calc.js -------------------------------------


def recovery(fall_pct):
    return {"gain_pct": (1 / (1 - fall_pct / 100) - 1) * 100}


def leverage(own, borrowed, rate_pct, months, move_pct):
    position = own + borrowed
    interest = borrowed * rate_pct / 100 * months / 12
    pnl = position * move_pct / 100 - interest
    return {"position": position, "leverage": position / own, "interest": interest, "pnl": pnl,
            "return_pct": pnl / own * 100, "breakeven_pct": interest / position * 100,
            "wipeout_pct": -(own - interest) / position * 100, "owed": max(0.0, -pnl - own)}


def cost_drag(amount, years, rate_pct, extra_cost_pp):
    low = amount * (1 + rate_pct / 100) ** years
    high = amount * (1 + (rate_pct - extra_cost_pp) / 100) ** years
    return {"low": low, "high": high, "diff": low - high, "diff_pct": (low / high - 1) * 100,
            "share_pct": (1 - high / low) * 100}


def real_return(amount, years, rate_pct, inflation_pct):
    n, i = rate_pct / 100, inflation_pct / 100
    nominal = amount * (1 + n) ** years
    return {"nominal": nominal, "real": nominal / (1 + i) ** years, "real_rate_pct": ((1 + n) / (1 + i) - 1) * 100,
            "approx_pct": (n - i) * 100, "needed": amount * (1 + i) ** years}


MIRROR = {"recovery": recovery, "leverage": leverage, "costDrag": cost_drag, "realReturn": real_return}


def matches(calc, inputs, expect):
    """expect maps output -> [value, decimals]; the output, rounded so, must equal value."""
    got = MIRROR[calc](**inputs)
    return all(round(got[k], d) == round(v, d) for k, (v, d) in expect.items())


def fewest_decimals(calc, exact, cases):
    """Round every non-integer input to d decimals, d = 1..6; return the first d at which
    the default and every case reproduce. cases: list of (inputs_exact, expect)."""
    for d in range(1, 7):
        rnd = lambda inp: {k: (int(v) if float(v).is_integer() else round(v, d)) for k, v in inp.items()}
        if all(matches(calc, rnd(i), e) for i, e in cases):
            return rnd(exact), [{"calc": calc, "inputs": rnd(i), "expect": e} for i, e in cases]
    raise SystemExit(f"{calc}: no precision up to 6 decimals reproduces the post's figures")


out = {"_note": "GENERATED by scripts/derive_tool_defaults.py — do not edit by hand. "
                "Defaults for the on-page calculators, and the cases each must reproduce."}

# ---- loss recovery and leverage (The arithmetic of losses; Leverage and margin) ----
a, lv = risk["arithmetic_of_losses"], risk["leverage"]
m = lv["mtf"]
cases = [({"fall_pct": abs(a["gfc_fall_pct"])}, {"gain_pct": [a["gfc_gain_needed_pct"], 1]})]
cases += [({"fall_pct": r["loss_pct"]}, {"gain_pct": [r["gain_needed_pct"], 1]}) for r in a["recovery_table"]]
rec_default, rec_cases = fewest_decimals("recovery", cases[0][0], cases)

base = {"own": m["own"], "borrowed": m["borrowed"], "rate_pct": m["rate_pct"], "months": m["months"]}
cases = []
for s in m["scenarios"]:
    cases.append(({**base, "move_pct": s["move_pct"]},
                  {"pnl": [s["pnl"], 0], "return_pct": [s["return_on_own_pct"], 1], "interest": [m["interest"], 0],
                   "breakeven_pct": [m["breakeven_move_pct"], 1], "wipeout_pct": [m["wipeout_move_pct"], 1]}))
# The multiplier table: no interest, own capital 100, borrowed so that position / own = L.
# The post caps the table at -100%; the calculator shows the full loss and what's still owed,
# so a capped cell is checked as "return at or below -100".
for row in lv["table"]:
    for L in (2, 5, 10):
        if row[f"x{L}"] > -100:
            cases.append(({"own": 100, "borrowed": 100 * (L - 1), "rate_pct": 0, "months": 12, "move_pct": row["move_pct"]},
                          {"return_pct": [row[f"x{L}"], 1]}))
move_default = -10
assert any(s["move_pct"] == move_default for s in m["scenarios"])
lev_default, lev_cases = fewest_decimals("leverage", {**base, "move_pct": move_default}, cases)
out["loss-recovery"] = {"defaults": {**rec_default, **lev_default}, "cases": rec_cases + lev_cases}

# ---- cost drag (Expense ratio: direct vs regular plan) ---------------------------
ea = mf["expense_ratio"]["active_fund"]
rows = {r["date"]: r for r in csv.DictReader(open(os.path.join(ROOT, ea["csv_path"].lstrip("/")), encoding="utf-8"))}
s, e = rows[ea["start"]], rows[ea["end"]]
years = (date.fromisoformat(ea["end"]) - date.fromisoformat(ea["start"])).days / 365.25
cagr = {k: (float(e[f"nav_{k}_growth"]) / float(s[f"nav_{k}_growth"])) ** (1 / years) - 1 for k in ("direct", "regular")}
assert round(cagr["direct"] * 100, 2) == round(ea["direct_cagr"], 2) and round(cagr["regular"] * 100, 2) == round(ea["regular_cagr"], 2), \
    "NAV CSV no longer gives mf.yml's CAGRs"
exact = {"amount": 100000, "years": years, "rate_pct": cagr["direct"] * 100,
         "extra_cost_pp": (cagr["direct"] - cagr["regular"]) * 100}
expect = {"low": [ea["lumpsum_1lakh_direct"], 0], "high": [ea["lumpsum_1lakh_regular"], 0],
          "diff": [ea["lumpsum_difference"], 0], "diff_pct": [ea["difference_pct"], 1]}
cd_default, cd_cases = fewest_decimals("costDrag", exact, [(exact, expect)])
# The post's rule of thumb: "each 1% of annual fee costs roughly 20–25% of your final
# corpus over 30 years". Recorded here so the claim is checked, not just asserted.
thumb = {f"{g}": round(cost_drag(100000, 30, g, 1)["share_pct"], 1) for g in (8, 10, 12)}
assert all(20 <= v <= 25 for v in thumb.values()), f"rule of thumb no longer holds: {thumb}"
out["cost-drag"] = {"defaults": cd_default, "cases": cd_cases, "rule_of_thumb_share_pct_30y_1pp": thumb}

# ---- real return (Inflation and real returns) -------------------------------------
inf = risk2["inflation"]
N = inf["years"]
# growth_factor / cpi_factor are the unrounded cumulative factors; the rupee totals
# in the post are rounded, and rates backed out of them can miss by ₹1.
infl = (inf["cpi_factor"] ** (1 / N) - 1) * 100
cases = []
for k in ("fd", "idx", "gilt"):  # fd first: it is the default
    sm = inf["summary"][k]
    rate = (sm["growth_factor"] ** (1 / N) - 1) * 100
    cases.append(({"amount": 100000, "years": N, "rate_pct": rate, "inflation_pct": infl},
                  {"nominal": [sm["lakh_nominal"], 0], "real": [sm["lakh_real"], 0],
                   "real_rate_pct": [sm["real_cagr_pct"], 1], "needed": [inf["lakh_needed"], 0]}))
rr_default, rr_cases = fewest_decimals("realReturn", cases[0][0], cases)
out["real-return"] = {"defaults": rr_default, "cases": rr_cases}

with open(OUT, "w", encoding="utf-8") as fh:
    json.dump(out, fh, ensure_ascii=False, indent=2)
    fh.write("\n")
print("wrote", os.path.relpath(OUT, ROOT))
for k in ("loss-recovery", "cost-drag", "real-return"):
    print(" ", k, json.dumps(out[k]["defaults"]), f"({len(out[k]['cases'])} cases)")
